//go:build ignore

// gen writes data.go: the stat allocations of every random-suffix bonus list (ItemBonus type 2:
// stat id, share of the budget in 1/10000) and the stat budget per item level (RandPropPoints:
// Good/Superior/Epic × slot column 0–4), read from the WoW Forever client tables wago.tools
// publishes.
//
//	go run gen.go -build 1.60.1.70959
package main

import (
	"bytes"
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
)

func main() {
	build := flag.String("build", "", "wowf client build, e.g. 1.60.1.70959 (https://wago.tools/api/builds)")
	flag.Parse()
	if *build == "" {
		log.Fatal("-build is required")
	}
	type alloc struct{ order, stat, share int }
	allocs := map[int][]alloc{}
	for _, r := range table(*build, "ItemBonus") {
		if r["Type"] != "2" {
			continue
		}
		allocs[num(r["ParentItemBonusListID"])] = append(allocs[num(r["ParentItemBonusListID"])],
			alloc{num(r["OrderIndex"]), num(r["Value_0"]), num(r["Value_1"])})
	}
	type budget [3][5]int
	budgets := map[int]budget{}
	for _, r := range table(*build, "RandPropPoints") {
		var b budget
		any := false
		for q, name := range []string{"Good", "Superior", "Epic"} {
			for c := 0; c < 5; c++ {
				b[q][c] = num(r[fmt.Sprintf("%s_%d", name, c)])
				any = any || b[q][c] != 0
			}
		}
		if any {
			budgets[num(r["ID"])] = b
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen.go from wago.tools WoW Forever build %s; DO NOT EDIT.\n\n", *build)
	b.WriteString("package upgrade\n\n")
	fmt.Fprintf(&b, "// Build is the client build the tables were read from.\nconst Build = %q\n\n", *build)
	b.WriteString("var bonusAllocs = map[int64][]alloc{\n")
	for _, id := range sortedKeys(allocs) {
		a := allocs[id]
		sort.Slice(a, func(i, j int) bool { return a[i].order < a[j].order })
		fmt.Fprintf(&b, "\t%d: {", id)
		for i, x := range a {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "{%d, %d}", x.stat, x.share)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n// randProp[item level] = [Good, Superior, Epic][slot column 0..4]\nvar randProp = map[int][3][5]int{\n")
	for _, lvl := range sortedKeys(budgets) {
		x := budgets[lvl]
		fmt.Fprintf(&b, "\t%d: {{%s}, {%s}, {%s}},\n", lvl, ints(x[0]), ints(x[1]), ints(x[2]))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("data.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d bonus lists, %d item levels", len(allocs), len(budgets))
}

func ints(a [5]int) string {
	s := ""
	for i, v := range a {
		if i > 0 {
			s += ", "
		}
		s += strconv.Itoa(v)
	}
	return s
}

func sortedKeys[V any](m map[int]V) []int {
	k := make([]int, 0, len(m))
	for x := range m {
		k = append(k, x)
	}
	sort.Ints(k)
	return k
}

func num(s string) int {
	n, err := strconv.Atoi(s)
	if err != nil {
		log.Fatalf("not a number: %q", s)
	}
	return n
}

func table(build, name string) []map[string]string {
	url := "https://wago.tools/db2/" + name + "/csv?build=" + build
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 200))
		log.Fatalf("%s: %s %s", url, resp.Status, body)
	}
	recs, err := csv.NewReader(resp.Body).ReadAll()
	if err != nil || len(recs) == 0 {
		log.Fatalf("%s: %v", url, err)
	}
	var rows []map[string]string
	for _, rec := range recs[1:] {
		m := map[string]string{}
		for i, h := range recs[0] {
			m[h] = rec[i]
		}
		rows = append(rows, m)
	}
	return rows
}
