//go:build ignore

// gen writes names_data.go: the random-suffix name ("of the Eagle") of every item bonus list
// that has one, read from the WoW Forever client tables wago.tools publishes. ItemBonus rows of
// type 5 point a bonus list at an ItemNameDescription row; that row's Description_lang is the
// suffix shown after the item name in game.
//
//	go run gen.go -build 1.60.1.70959
package main

import (
	"bytes"
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	build := flag.String("build", "", "wowf client build, e.g. 1.60.1.70959 (https://wago.tools/api/builds)")
	flag.Parse()
	if *build == "" {
		log.Fatal("-build is required")
	}
	descs := table(*build, "ItemNameDescription")
	names := map[string]string{}
	for _, r := range descs {
		names[r["ID"]] = r["Description_lang"]
	}
	out := map[int64]string{}
	for _, r := range table(*build, "ItemBonus") {
		if r["Type"] != "5" {
			continue
		}
		name, ok := names[r["Value_0"]]
		// Random suffixes all read "of …"; this skips other name descriptions (e.g. "Test").
		if !ok || !strings.HasPrefix(name, "of ") {
			continue
		}
		id, err := strconv.ParseInt(r["ParentItemBonusListID"], 10, 64)
		if err != nil {
			log.Fatal(err)
		}
		out[id] = name
	}
	ids := make([]int64, 0, len(out))
	for id := range out {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen.go from wago.tools WoW Forever build %s; DO NOT EDIT.\n\n", *build)
	b.WriteString("package suffix\n\n")
	fmt.Fprintf(&b, "// Build is the client build the table was read from.\nconst Build = %q\n\n", *build)
	b.WriteString("var bonusName = map[int64]string{\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%d: %q,\n", id, out[id])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("names_data.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d bonus lists with a suffix name", len(ids))
}

func table(build, name string) []map[string]string {
	url := "https://wago.tools/db2/" + name + "/csv?build=" + build
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 200))
		log.Fatalf("%s: %s %s", url, resp.Status, body)
	}
	recs, err := csv.NewReader(resp.Body).ReadAll()
	if err != nil {
		log.Fatalf("%s: %v", url, err)
	}
	if len(recs) == 0 {
		log.Fatalf("%s: empty", url)
	}
	var rows []map[string]string
	for _, rec := range recs[1:] {
		m := map[string]string{}
		for i, h := range recs[0] {
			m[h] = rec[i]
		}
		rows = append(rows, m)
	}
	return rows
}
